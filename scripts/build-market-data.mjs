/**
 * Regenerate the annual US equity / CPI series in src/constants.js from the bundled Shiller
 * monthly data (src/data/shiller.js: S&P composite price, dividends, CPI — 1871-01..2023-06).
 *
 * EQUITY: calendar-year S&P 500 total returns (dividends reinvested) from Damodaran's NYU Stern
 * dataset, committed as src/data/damodaranReturns.json with provenance (audit: research/
 * market-data-audit-aug-2026.md). Shiller's monthly-average prices agree on the long-run mean
 * (10.1% vs 9.9%) but drift on single years; the published calendar-year series is the
 * citable one, so it is the source. INFLATION: CPI Jan(Y+1)/Jan(Y) − 1 from the bundled
 * Shiller CPI (2023-24 appended from published CPI-U figures).
 *
 * Run: node scripts/build-market-data.mjs   (rewrites the two blocks in src/constants.js)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import shiller from '../src/data/shiller.js';
import { readFileSync as rf } from 'node:fs';
const DAMODARAN = JSON.parse(rf(new URL('../src/data/damodaranReturns.json', import.meta.url), 'utf8'));

const { P, D, CPI } = shiller;
const [sy, sm] = shiller.start.split('-').map(Number);
const idx = (y, m) => (y - sy) * 12 + (m - sm);
const tr = [1];
for (let i = 1; i < P.length; i++) tr[i] = tr[i - 1] * (P[i] + D[i] / 12) / P[i - 1];

const FIRST = 1928, LAST_SHILLER = 2022;
// WORLD, not US: UBS/Credit Suisse Global Investment Returns Yearbook 2024 — 1900-2023 real
// returns US 6.6%/yr vs World 5.0%/yr. The S&P series is haircut by the gap so a world-tracker
// holder is not modelled on US exceptionalism. Not a setting. Same constant as ladderEngine.
const WORLD_EQUITY_HAIRCUT = 0.015;
const APPEND = { 2023: { eq: 0.2629, inf: 0.034 }, 2024: { eq: 0.2502, inf: 0.029 } };
const EQ = {}, INF = {};
for (let y = FIRST; y <= LAST_SHILLER; y++) {
  const a = idx(y, 1), b = idx(y + 1, 1);
  INF[y] = +(CPI[b] / CPI[a] - 1).toFixed(4);
}
for (const [y, v] of Object.entries(APPEND)) INF[y] = v.inf;
for (let y = FIRST; y <= 2024; y++) {
  const row = DAMODARAN.years[y];
  if (!row || !Number.isFinite(row.sp500TotalReturn)) throw new Error('Damodaran row missing for ' + y);
  EQ[y] = +(((1 + row.sp500TotalReturn) * (1 - WORLD_EQUITY_HAIRCUT)) - 1).toFixed(4);
}

const fmt = (obj) => {
  const ys = Object.keys(obj).map(Number).sort((a, b) => a - b);
  const lines = [];
  for (let i = 0; i < ys.length; i += 5) {
    lines.push('  ' + ys.slice(i, i + 5).map((y) => `${y}: ${obj[y].toFixed(4)}`).join(', '));
  }
  return lines.join(',\n');
};
const n = Object.keys(EQ).length;
let g = 1, gr = 1;
for (const y of Object.keys(EQ)) { g *= 1 + EQ[y]; gr *= (1 + EQ[y]) / (1 + INF[y]); }
const geoN = ((g ** (1 / n) - 1) * 100).toFixed(2), geoR = ((gr ** (1 / n) - 1) * 100).toFixed(2);

const eqBlock = `// ============================================================================
// HISTORICAL DATA - WORLD EQUITY, nominal (${FIRST}-2024) - ${n} years
// GENERATED by scripts/build-market-data.mjs: Damodaran's calendar-year S&P 500 total return
// (src/data/damodaranReturns.json) LESS a ${(WORLD_EQUITY_HAIRCUT*100).toFixed(1)}pp/yr world haircut (Yearbook 2024: US 6.6% vs
// World 5.0% real, 1900-2023) — a world-tracker holder is not modelled on US returns. Geometric
// mean ${geoN}% nominal / ${geoR}% real. Audit: research/market-data-audit-aug-2026.md.
// Do not hand-edit — rerun the script.
// ============================================================================
export const EQUITY_RETURNS = {
${fmt(EQ)}
};

// ============================================================================
// HISTORICAL DATA - US CPI INFLATION (${FIRST}-2024) - ${n} years (Shiller CPI, Jan/Jan; same script)
// ============================================================================
export const INFLATION = {
${fmt(INF)}
};
`;

const file = new URL('../src/constants.js', import.meta.url);
const src = readFileSync(file, 'utf8');
const start = src.indexOf('// ============================================================================\n// HISTORICAL DATA - ');
const endMarker = '// ============================================================================\n// SCENARIO DEFINITIONS';
const end = src.indexOf(endMarker);
if (start < 0 || end < 0) throw new Error('markers not found');
writeFileSync(file, src.slice(0, start) + eqBlock + '\n' + src.slice(end));
console.log(`Wrote ${n} years: geo nominal ${geoN}% real ${geoR}%`);
// Canned-scenario helper: print a decade's equity/inflation for the SCENARIOS block
const dec = (from) => ({ equity: Array.from({ length: 10 }, (_, i) => EQ[from + i]), inflation: Array.from({ length: 10 }, (_, i) => INF[from + i]) });
for (const [name, from] of [['GREAT_DEPRESSION', 1929], ['STAGFLATION_70S', 1973], ['LOST_DECADE_2000S', 2000], ['GFC_2008', 2008]]) {
  const d = dec(from);
  console.log(name, from, JSON.stringify(d.equity.map((v) => +v.toFixed(2))), JSON.stringify(d.inflation.map((v) => +v.toFixed(2))));
}
