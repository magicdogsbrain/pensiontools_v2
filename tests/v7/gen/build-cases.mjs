/**
 * Writes tests/v7/c/cases.pairs.json: the all-pairs list, the 48 core cases and the 10 age-boundary cases
 * (test plan 1.4). Deterministic. Run with  npm run v7:cases  (node tests/v7/gen/build-cases.mjs).
 *
 * The file is committed; pairs.test.js regenerates it and fails when it differs, so a change to the input list
 * forces a regenerate and shows the difference in review.
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pairCases, DIMENSIONS } from './pairs.mjs';

/** household (2) × final-salary (yes, no) × State Pension (yes, no) × risk (3) × start (now, later) on one middle-of-the-road person: 48. */
export function coreCases() {
  const out = [];
  for (const household of ['single', 'couple']) {
    for (const fs of [false, true]) {
      for (const sp of [true, false]) {
        for (const risk of ['cautious', 'balanced', 'adventurous']) {
          for (const later of [false, true]) {
            const inputs = { household, you: { pot: 250000, age: 60 }, risk };
            if (fs) inputs.you.finalSalary = { has: true, yearly: 9000, fromAge: 65 };
            if (!sp) inputs.you.statePension = { kind: 'none' };
            if (later) inputs.start = { kind: 'age', age: 62 };
            if (household === 'couple') inputs.partner = { age: 58, pot: 100000 };
            out.push({ name: ['core', household, fs ? 'fs' : 'noFs', sp ? 'sp' : 'noSp', risk, later ? 'from62' : 'now'].join('·'), inputs });
          }
        }
      }
    }
  }
  return out;
}

/** Each age of the list, single, £250,000, everything else left alone: 10. */
export function ageCases() {
  return DIMENSIONS.find((d) => d.name === 'age').values.map((v) => {
    const inputs = {};
    v.set(inputs);
    inputs.you.pot = 250000;
    return { name: `age·${inputs.you.age}`, inputs };
  });
}

export function buildCases() {
  return {
    what: 'Generated by tests/v7/gen/build-cases.mjs from tests/v7/gen/pairs.mjs. Do not edit by hand: run npm run v7:cases.',
    dimensions: DIMENSIONS.map((d) => ({ name: d.name, values: d.values.map((v) => v.id) })),
    pairs: pairCases(),
    core: coreCases(),
    ages: ageCases()
  };
}

export const CASES_PATH = resolve(process.cwd(), 'tests/v7/c/cases.pairs.json');

/** One case per line, so a difference reads in review. */
export function casesText(cases) {
  const line = (c) => '    ' + JSON.stringify(c);
  return '{\n' +
    `  "what": ${JSON.stringify(cases.what)},\n` +
    `  "dimensions": ${JSON.stringify(cases.dimensions)},\n` +
    `  "pairs": [\n${cases.pairs.map(line).join(',\n')}\n  ],\n` +
    `  "core": [\n${cases.core.map(line).join(',\n')}\n  ],\n` +
    `  "ages": [\n${cases.ages.map(line).join(',\n')}\n  ]\n}\n`;
}

if (process.argv[1] && process.argv[1].endsWith('build-cases.mjs')) {
  const cases = buildCases();
  writeFileSync(CASES_PATH, casesText(cases));
  console.log(`${cases.pairs.length} pair cases, ${cases.core.length} core, ${cases.ages.length} ages → ${CASES_PATH}`);
}
